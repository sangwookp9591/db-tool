import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const base = process.env.AXDB_UPDATE_TEST_URL || 'http://127.0.0.1:5186';
await mkdir('../docs/design-shots', { recursive: true });
const browser = await chromium.launch({ headless: true });
const errors = [];
try {
  for (const theme of ['midnight', 'daylight']) {
    const context = await browser.newContext({ viewport: { width: 1280, height: 800 }, reducedMotion: 'reduce' });
    await context.addInitScript(theme => localStorage.setItem('axdb-theme', theme), theme);
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${base}/?update=available`);
    const badge = page.getByRole('button', { name: '업데이트 0.3.0', exact: true });
    await badge.waitFor({ timeout: 25_000 });
    await page.screenshot({ path: `../docs/design-shots/update-badge-${theme}.png` });
    await badge.click();
    const dialog = page.getByRole('dialog', { name: 'AxDB 업데이트' });
    await dialog.waitFor();
    const notes=dialog.getByRole('region',{name:'릴리스 노트',exact:true});
    assert.equal(await notes.locator('script').count(), 0);
    assert.match(await notes.textContent(), /<script>alert/);
    assert.equal(await notes.locator('a[href^="javascript:"]').count(), 0);
    assert.equal(await notes.locator('[data-slot="changelog-timeline"]').count(), 1);
    assert.match(await notes.textContent(), /자동 업데이트와 릴리스 노트/);
    assert.match(await notes.textContent(), /연결 안정성 개선/);
    assert.match(await notes.textContent(), /작업을 저장하세요/);
    assert.match(await notes.textContent(), /업데이트 후 다시 시작하세요/);
    assert.equal(await notes.locator('a[href="https://github.com/sangwookp9591/db-tool/releases"]').count()>=1, true);
    assert.match(await dialog.innerText(), /2026/);
    await page.screenshot({ path: `../docs/design-shots/update-notes-${theme}.png` });
    await page.getByRole('button', { name: '지금 업데이트', exact: true }).click();
    await page.getByRole('progressbar').waitFor();
    assert.equal(await page.getByRole('button', { name: '나중에', exact: true }).isDisabled(), true);
    await page.screenshot({ path: `../docs/design-shots/update-progress-${theme}.png` });
    const restart = page.getByRole('button', { name: '다시 시작', exact: true });
    await restart.waitFor();
    await page.screenshot({ path: `../docs/design-shots/update-restart-${theme}.png` });
    await page.evaluate(() => { window.updateRestarted = false; window.addEventListener('axdb-mock-restart', () => { window.updateRestarted = true; }); });
    await restart.click();
    assert.equal(await page.evaluate(() => window.updateRestarted), true);
    await page.goto(`${base}/?update=none`);
    await page.getByRole('button', { name: 'Workspace settings', exact: true }).click();
    await page.getByRole('button', { name: '업데이트 확인…', exact: true }).click();
    await page.getByText('최신 버전입니다', { exact: true }).waitFor();
    await page.screenshot({ path: `../docs/design-shots/update-latest-${theme}.png` });
    await context.close();
  }
  const page = await browser.newPage();
  await page.goto(`${base}/?update=error`);
  await page.waitForTimeout(11_000);
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.equal(await page.getByRole('button', { name: '업데이트 0.3.0', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Workspace settings', exact: true }).click();
  await page.getByRole('button', { name: '업데이트 확인…', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '업데이트를 확인할 수 없습니다' }).waitFor();
  await page.goto(`${base}/?update=available`);
  await page.getByRole('button', { name: 'Workspace settings', exact: true }).click();
  await page.getByRole('button', { name: '업데이트 확인…', exact: true }).click();
  await page.getByRole('button', { name: '이 버전 건너뛰기', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: '업데이트 0.3.0', exact: true }).count(), 0);
  await page.getByRole('button', { name: '업데이트 확인…', exact: true }).click();
  await page.getByRole('button', { name: '지금 업데이트', exact: true }).waitFor();
  await page.getByRole('button', { name: '나중에', exact: true }).click();
  const automatic = page.getByRole('checkbox', { name: '업데이트 자동 확인' });
  await automatic.uncheck();
  assert.equal(await automatic.isChecked(), false);
  assert.deepEqual(errors, []);
  console.log('PASS: both themes badge → safe Markdown → progress → installed → mock restart; latest, silent automatic error, manual error, skip/manual override, auto toggle.');
} finally { await browser.close(); }
